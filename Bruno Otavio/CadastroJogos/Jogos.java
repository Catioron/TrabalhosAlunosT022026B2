package CadastroJogos;

public class Jogos {


		private String nome;
		private String genero;
		private int id;

		public Jogos() {
		}

		public String getNome() {
			return nome;
		}

		public void setNome(String nome) {
			this.nome = nome;
		}

		public String getGenero() {
			return genero;
		}

		public void setGenero(String genero) {
			this.genero = genero;
		}

		public int getID() {
			return id;
		}

		public void setID(int id) {
			this.id = id;
		}
}
		

			
